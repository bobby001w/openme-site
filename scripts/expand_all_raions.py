# find all raion pages and append if word_count<400
for lang in ('','ru'):
    base = os.path.join(root, 'raiony') if lang=='' else os.path.join(root,'ru','raiony')
    if not os.path.exists(base):
        continue
    for entry in os.listdir(base):
        pdir = os.path.join(base, entry)
        idx = os.path.join(pdir, 'index.html')
        if not os.path.exists(idx):
            continue
        rel = os.path.relpath(idx, root).replace('\\','/')
        txt = open(idx,'r',encoding='utf-8').read()
        m_main = re.search(r'<main[^>]*>(.*?)</main>', txt, re.I|re.S)
        main_html = m_main.group(1) if m_main else txt
        main_text = re.sub('<script[\s\S]*?</script>','', main_html)
        main_text = re.sub('<[^>]+>',' ', main_text)
        words = re.findall(r"\b[\wА-Яа-яЁёЇїІіЄєҐґ'-]+\b", main_text)
        wc = len(words)
        # target slug
        slug = entry
        # normalize slug keys
        key = slug
        if slug.endswith('-raion'):
            key = slug
        if key not in snippets:
            # try simplified keys
            short = slug.split('-')[0]
            if short in snippets:
                key = short
        if key not in snippets:
            continue
        if wc < 420:
            print('extending', rel, 'wc', wc)
            # build block
            lang_code = 'ru' if lang=='ru' else 'uk'
            blocks = snippets[key][lang_code]
            add = '\n'.join(f'<p>{b}</p>' for b in blocks)
            # add a small FAQ
            if lang_code=='uk':
                faq = '<details><summary>Часті питання</summary><p>Ми виїжджаємо швидко та працюємо акуратно, ціни називаємо після опису проблеми.</p></details>'
            else:
                faq = '<details><summary>Частые вопросы</summary><p>Мы выезжаем быстро и работаем аккуратно, цены называем после описания проблемы.</p></details>'
            insert = add + '\n' + faq + '\n'
            # insert before </main>
            newtxt = txt.replace('</main>', insert + '\n  </main>')
            open(idx,'w',encoding='utf-8').write(newtxt)
            print('written', idx)
print('done')
